const iconTextureCache = new Map();

/**
 * Genera una textura CanvasTexture en alta resolución (128x128) con el icono Lucide SVG especificado.
 */
export function getLucideIconTexture(name, color = '#1c1917', strokeWidth = 2.4) {
  const safeName = LUCIDE_SVG_PATHS[name] ? name : 'compass';
  const cacheKey = `${safeName}_${color}_${strokeWidth}`;

  if (iconTextureCache.has(cacheKey)) {
    return iconTextureCache.get(cacheKey);
  }

  if (typeof document === 'undefined') {
    // Entorno de test / SSR sin DOM
    const dummyTexture = new THREE.Texture();
    iconTextureCache.set(cacheKey, dummyTexture);
    return dummyTexture;
  }

  const canvas = document.createElement('canvas');
  canvas.width = 128;
  canvas.height = 128;
  const ctx = canvas.getContext('2d');

  const texture = new THREE.CanvasTexture(canvas);
  texture.minFilter = THREE.LinearFilter;
  texture.magFilter = THREE.LinearFilter;

  const svgInner = LUCIDE_SVG_PATHS[safeName];
  const svgString = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${svgInner}</svg>`;

  try {
    const img = new Image();
    const blob = new Blob([svgString], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);

    img.onload = () => {
      ctx.clearRect(0, 0, 128, 128);
      ctx.drawImage(img, 0, 0, 128, 128);
      texture.needsUpdate = true;
      URL.revokeObjectURL(url);
    };

    img.onerror = () => {
      URL.revokeObjectURL(url);
    };

    img.src = url;
  } catch (e) {
    console.warn('Error rasterizando icono Lucide a textura:', e);
  }

  iconTextureCache.set(cacheKey, texture);
  return texture;
}

/**
 * Componente 3D para renderizar un icono vectorial Lucide nítido sin emojis.
 */
export function LucideVRIcon({
  name,
  size = 0.08,
  color = '#1c1917',
  strokeWidth = 2.4,
  position = [0, 0, 0]
}) {
  const texture = useMemo(
    () => getLucideIconTexture(name, color, strokeWidth),
    [name, color, strokeWidth]
  );

  return (
    <mesh position={position}>
      <planeGeometry args={[size, size]} />
      <meshBasicMaterial map={texture} transparent alphaTest={0.01} />
    </mesh>
  );
}

export default LucideVRIcon;
